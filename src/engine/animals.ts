export function drawAnimal(
  ctx: CanvasRenderingContext2D,
  animal: AnimalId,
  x: number,
  y: number,
  pixel: number,
  facing: 1 | -1,
  frame: number,
  highlight: boolean,
): void {
  const grid = GRIDS[animal];
  const pal = PALETTES[animal];
  const bob = Math.round(Math.sin(frame) * pixel * 0.15);
  const leg = frame % 2 === 0 ? 0 : 1;
  ctx.save();
  ctx.imageSmoothingEnabled = false;
  ctx.translate(Math.round(x), Math.round(y + bob));
  ctx.scale(facing, 1);
  ctx.fillStyle = "rgba(0,0,0,0.28)";
  ctx.fillRect(-5 * pixel, 11 * pixel, 10 * pixel, 2 * pixel);
  for (let row = 0; row < 12; row += 1) {
    for (let col = 0; col < 12; col += 1) {
      const idx = grid[row]?.[col] ?? 0;
      if (!idx) continue;
      let drawRow = row;
      if (row >= 8) drawRow = row + (col < 4 ? -leg : leg);
      ctx.fillStyle = pal[idx] ?? pal[1];
      ctx.fillRect((col - 6) * pixel, (drawRow - 12) * pixel, pixel, pixel);
    }
  }
  if (highlight) {
    ctx.strokeStyle = "rgba(240, 193, 74, 0.95)";
    ctx.lineWidth = 1;
    ctx.strokeRect(-7 * pixel, -13 * pixel, 14 * pixel, 14 * pixel);
  }
  ctx.restore();
}
