export function animalFor(id: string): AnimalId {
  let hash = 0;
  for (let i = 0; i < id.length; i += 1) hash = (hash * 31 + id.charCodeAt(i)) | 0;
  return ANIMALS[Math.abs(hash) % ANIMALS.length];
}

